#!/usr/bin/env python3
"""Generate the deterministic mock datasets in aura/data.aura (seeded; committed output).

Ground truth is produced by hidden "business" rules that the policies only approximate,
so the evolution loop has something to measure. NOTE: the labels are synthetic and the
v2 policies were written against the same domain rules, so v2 scores are optimistic.
"""
import random
from pathlib import Path

R = random.Random(20261027)
import os
OUT = Path(os.environ.get("SCM_DATA_OUT") or Path(__file__).resolve().parents[1] / "aura" / "data.aura")


def b(x):
    return "#t" if x else "#f"


def f(x):
    return f"{x:.3f}"


def edi_history(n=60, R=R):
    rows = []
    for i in range(n):
        pct = round(R.choice([-1, 1]) * R.uniform(0.05, 0.45), 3)
        exposure = R.randrange(200_000, 1_600_000, 10_000)
        frozen = R.random() < 0.12
        conf = round(R.uniform(0.35, 0.98), 2)
        # hidden truth: a planner really had to arbitrate
        needed = abs(pct) >= 0.20 and exposure >= 750_000 and not frozen and conf >= 0.70
        rows.append(f'(hash "id" "EDI-{i:03d}" "pct" {f(pct)} "exposure" {exposure} "frozen" {b(frozen)} '
                    f'"confidence" {conf} "needed" {b(needed)})')
    return rows


def claims(n=48, R=R):
    rows = []
    for i in range(n):
        kind = R.choices(["supplier", "forecast", "market", "noise"], [0.35, 0.25, 0.25, 0.15])[0]
        ei = lt = fb = mm = False
        bias = 0.0
        if kind == "supplier":
            ei, lt = True, True
            fb = R.random() < 0.3
            bias = round(R.uniform(0.0, 0.08), 3) if fb else 0.0
            truth = "supplier-delay"
        elif kind == "forecast":
            fb = True
            bias = round(R.uniform(0.03, 0.25), 3)   # often <= 0.1: v1 under-detects
            ei = R.random() < 0.4
            truth = "demand-forecast-error"
        elif kind == "market":
            mm = True
            ei = R.random() < 0.5
            truth = "demand-forecast-error"
        else:
            ei = R.random() < 0.5
            truth = "unknown"
        amount = R.randrange(20_000, 260_000, 1_000)
        rows.append(f'(hash "id" "CLM-{i:03d}" "amount" {amount} "edi-increase" {b(ei)} "lead-time-miss" {b(lt)} '
                    f'"forecast-bias" {b(fb)} "bias-amount" {f(bias)} "market-mismatch" {b(mm)} "truth" (quote {truth}))')
    return rows


def risk_events(n=40, R=R, H=None):
    # H: separate stream for the hidden outcome fields, so the visible train rows are unchanged
    H = H or random.Random(20261027 + 7)
    rows = []
    for i in range(n):
        lvl = R.choices(["high", "medium", "low"], [0.25, 0.45, 0.30])[0]
        days = round(R.uniform(1.5, 14.0), 1)
        rebalance_ok = R.random() < 0.85      # network stock exists at a sister plant
        lead = R.choice([4, 6, 8])            # days until the next regular delivery
        # cost model v2 (hidden): does the risk materialize, sister-plant transfer time,
        # alternative-supplier lead time.  Policies only see (level, inventory-days).
        hits = H.random() < {"high": 0.8, "medium": 0.45, "low": 0.12}[lvl]
        transfer = H.choice([1, 2, 3, 4])
        alt_lead = transfer + H.choice([1, 2, 3])
        rows.append(f'(hash "id" "RSK-{i:03d}" "level" (quote {lvl}) "days" {days} "rebalance-ok" {b(rebalance_ok)} '
                    f'"lead" {lead} "hits" {b(hits)} "transfer" {transfer} "alt-lead" {alt_lead})')
    return rows


def main():
    L = [";; GENERATED by scripts/gen_data.py (seed 20261027; hold-out seed 20261029). Do not edit by hand.", ""]
    L.append("(define edi-history (list\n  " + "\n  ".join(edi_history()) + "))")
    L.append("(define claim-history (list\n  " + "\n  ".join(claims()) + "))")
    L.append("(define risk-history (list\n  " + "\n  ".join(risk_events()) + "))")
    # hold-out split: same generators, independent seed, never used for tuning
    HR = random.Random(20261029)
    L.append(";; hold-out rows (search tunes on the *-history train rows, reports on these)")
    L.append("(define edi-holdout (list\n  " + "\n  ".join(edi_history(120, HR)) + "))")
    L.append("(define claim-holdout (list\n  " + "\n  ".join(claims(96, HR)) + "))")
    L.append("(define risk-holdout (list\n  " + "\n  ".join(risk_events(80, HR, random.Random(20261029 + 7))) + "))")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
