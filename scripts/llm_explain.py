#!/usr/bin/env python3
"""Optional: turn results/demo.json into a short planner-facing explanation with an LLM.

The decision itself is always computed deterministically by the Aura agents; the LLM only
writes prose. Providers (OpenAI-compatible /chat/completions, see llm_client.py):
  --provider glm      : GLM-5.3 Flash ("glm-5.3-flash", coding-plan endpoint), key file $GLM_KEY_FILE
                        (default ~/.glm-key)
  --provider deepseek : model DeepSeek-V4.1-Flash (id "deepseek-flash"), key file $DEEPSEEK_KEY_FILE
                        (default ~/.deepseek-key)
  --provider minimax  : model MiniMax-M3.1-Flash, key file $MINIMAX_API_KEY_FILE, base URL $MINIMAX_BASE_URL
                        (both may be set in an env file passed with --env-file)
Keys are read from files only and are never printed or written to results.
"""
import argparse, json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from llm_client import PROVIDERS, call as llm_call, load_env_file  # noqa: E402

REPO = Path(__file__).resolve().parent.parent


def prompt(r, case):
    P = f"pkg.{case}"
    facts = {k[len(P) + 1:]: v for k, v in r.items() if k.startswith(P + ".")}
    evo = {k: v for k, v in r.items() if k.startswith("evo.") and (".v1." in k or ".v2.metrics." in k)}
    return [
        {"role": "system", "content": "You are a supply-chain planning assistant. Explain decisions using only the given facts. "
                                      "Answer in Chinese then English, at most 150 words each."},
        {"role": "user", "content": "Decision package:\n" + json.dumps(facts, ensure_ascii=False) +
                                    "\nPolicy evolution metrics:\n" + json.dumps(evo, ensure_ascii=False) +
                                    "\nExplain to the planner: what happened, why this plan, what to approve."},
    ]


def call(provider, messages, max_tokens=8000):
    r = llm_call(provider, messages, max_tokens=max_tokens)
    if not r["text"]:
        raise SystemExit(f"{provider}: empty answer (finish_reason={r['finish']})")
    return r["model"], r["text"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", choices=sorted(PROVIDERS), default="deepseek")
    ap.add_argument("--case", default="CASE-1")
    ap.add_argument("--env-file")
    a = ap.parse_args()
    if a.env_file:
        load_env_file(a.env_file)
    r = json.loads((REPO / "results/demo.json").read_text())
    model, text = call(a.provider, prompt(r, a.case))
    out = REPO / f"results/explain-{a.case}-{a.provider}.md"
    out.write_text(f"<!-- generated by {model}; prose only, decision computed deterministically -->\n\n{text}\n")
    print(f"wrote {out.relative_to(REPO)} ({model})")


if __name__ == "__main__":
    main()
